"""Builds OnionLLM font assets (DESIGN.md §2.2.1, §2.6).

Usage (from the repo root, with `pip install opentype-feature-freezer`):
    python tools/fonts/build_fonts.py --inter <Inter-4.1 dir> --jbm <JetBrainsMono-2.304 dir> --lucide <lucide-static package dir>

Inputs are the extracted release archives listed in tools/fonts/VERSION.
Outputs:
    OnionLLM/Resources/Fonts/*.ttf           Inter, InterTnum (tnum+cv11+ss01 frozen), JetBrains Mono, lucide
    OnionLLM/Resources/Fonts/LICENSES/*      licenses of the bundled fonts
    OnionLLM/Resources/Icons.cs              Lucide glyph constants (generated, do not edit)
"""
import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FONTS = ROOT / "OnionLLM" / "Resources" / "Fonts"
ICONS_CS = ROOT / "OnionLLM" / "Resources" / "Icons.cs"

INTER = ["Inter-Regular", "Inter-Medium", "Inter-SemiBold", "Inter-Bold"]
INTER_TNUM = {"Inter-Medium": "InterTnum-Medium", "Inter-SemiBold": "InterTnum-SemiBold"}
JBM = ["JetBrainsMono-Regular", "JetBrainsMono-Medium"]


def find(root: Path, name: str) -> Path:
    hits = sorted(root.rglob(name))
    if not hits:
        sys.exit(f"missing {name} under {root}")
    return hits[0]


def pascal(name: str) -> str:
    # "arrow-down-0-1" -> ArrowDown0_1 (keeps it distinct from "arrow-down-01" -> ArrowDown01)
    text = ""
    for part in (p for p in name.replace("_", "-").split("-") if p):
        if text[-1:].isdigit() and part[:1].isdigit():
            text += "_"
        text += part[:1].upper() + part[1:]
    return "_" + text if text[:1].isdigit() else text


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--inter", type=Path, required=True)
    parser.add_argument("--jbm", type=Path, required=True)
    parser.add_argument("--lucide", type=Path, required=True)
    args = parser.parse_args()

    FONTS.mkdir(parents=True, exist_ok=True)
    licenses = FONTS / "LICENSES"
    licenses.mkdir(exist_ok=True)

    for name in INTER:
        shutil.copyfile(find(args.inter, f"{name}.ttf"), FONTS / f"{name}.ttf")
    for source, target in INTER_TNUM.items():
        subprocess.run(
            [sys.executable, "-c", "import sys; from opentype_feature_freezer.cli import main; sys.argv[0] = 'pyftfeatfreeze'; main()",
             "-f", "tnum,cv11,ss01", "-S", "-U", "Tnum",
             str(FONTS / f"{source}.ttf"), str(FONTS / f"{target}.ttf")],
            check=True)
    for name in JBM:
        shutil.copyfile(find(args.jbm, f"{name}.ttf"), FONTS / f"{name}.ttf")
    shutil.copyfile(args.lucide / "font" / "lucide.ttf", FONTS / "lucide.ttf")

    shutil.copyfile(find(args.inter, "LICENSE.txt"), licenses / "Inter-OFL.txt")
    shutil.copyfile(find(args.jbm, "OFL.txt"), licenses / "JetBrainsMono-OFL.txt")
    shutil.copyfile(args.lucide / "LICENSE", licenses / "Lucide-ISC.txt")

    info = json.loads((args.lucide / "font" / "info.json").read_text(encoding="utf-8"))
    version = json.loads((args.lucide / "package.json").read_text(encoding="utf-8"))["version"]
    lines = [
        "// <auto-generated>",
        f"// Generated by tools/fonts/build_fonts.py from lucide-static {version}. Do not edit.",
        "// </auto-generated>",
        "namespace OnionLLM.Resources;",
        "",
        "/// <summary>Lucide glyphs for the <c>Lucide</c> font alias (DESIGN.md §2.6, §11.2).</summary>",
        "public static class Icons",
        "{",
        "    public const string FontFamily = \"Lucide\";",
        "",
    ]
    names = [pascal(name) for name in info]
    duplicates = {n for n in names if names.count(n) > 1}
    if duplicates:
        sys.exit(f"icon name collisions: {sorted(duplicates)}")
    for name in sorted(info):
        code = int(info[name]["encodedCode"].lstrip("\\"), 16)
        escaped = "\\u" + f"{code:04X}"
        lines.append(f"    public const string {pascal(name)} = \"{escaped}\";")
    lines.append("}")
    ICONS_CS.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"fonts -> {FONTS}\nicons -> {ICONS_CS} ({len(info)} glyphs)")


if __name__ == "__main__":
    main()

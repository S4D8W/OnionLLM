def color_lines(colors: dict[str, str]) -> list[str]:
    lines = []
    for key, value in colors.items():
        lines.append(f'    <Color x:Key="{key}">{value}</Color>')
    lines.append("")
    for key, value in colors.items():
        lines.append(f'    <SolidColorBrush x:Key="{key}Brush" Color="{value}" />')
    return lines


def shadow_lines(theme: int) -> list[str]:
    lines = []
    for key, values in SHADOWS.items():
        spec = values[theme]
        if spec is None:
            # Invisible but valid: WinUI rejects a zero blur radius when building the shadow mask.
            lines.append(f'    <Shadow x:Key="{key}" Brush="#00000000" Offset="0,0" Radius="1" Opacity="0" />')
        else:
            brush, offset, radius, opacity = spec
            lines.append(f'    <Shadow x:Key="{key}" Brush="{brush}" Offset="{offset}" Radius="{radius}" Opacity="{opacity}" />')
    return lines


def pascal(source_id: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in source_id.replace("_", "-").split("-"))


def write(name: str, lines: list[str]) -> None:
    cls = name.removesuffix(".xaml").replace(".", "")
    (OUT / name).write_text(HEADER.replace("{cls}", cls) + "\n".join(lines) + "\n" + FOOTER, encoding="utf-8")
    (OUT / (name + ".cs")).write_text(CODE_BEHIND.format(cls=cls), encoding="utf-8")


def number(value: float) -> str:
    return f"{value:g}"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    problems: list[str] = []

    write("Tokens.Primitives.xaml", color_lines(PALETTE))

    for theme, name in ((0, "Light"), (1, "Dark")):
        colors = {key: values[theme] for key, values in SEMANTIC.items()}
        hero = [
            "",
            '    <LinearGradientBrush x:Key="BrushHero" StartPoint="0,0" EndPoint="1,1">',
            f'        <GradientStop Color="{colors['ColorHeroStart']}" Offset="0" />',
            f'        <GradientStop Color="{colors['ColorHeroMid']}" Offset="0.55" />',
            f'        <GradientStop Color="{colors['ColorHeroEnd']}" Offset="1" />',
            "    </LinearGradientBrush>",
        ]
        logo = ["", f'    <FileImageSource x:Key="ImageLogo" File="{("onion_logo.png", "onion_logo_dark.png")[theme]}" />']
        write(f"Tokens.{name}.xaml", color_lines(colors) + hero + logo + [""] + shadow_lines(theme))

    core = palette.core_sources()
    for source_id in core:
        if source_id not in SOURCES:
            computed = palette.variants(core[source_id])
            problems.append(f"source '{source_id}' missing from DESIGN.md §2.1.6; computed {computed}")
    ids = sorted(set(SOURCES) | set(core))
    for theme, name, surfaces in ((0, "Light", palette.LIGHT_BACKGROUNDS), (1, "Dark", palette.DARK_BACKGROUNDS)):
        colors: dict[str, str] = {}
        for source_id in ids:
            light, dark, avatar_light, avatar_dark, initial = SOURCES.get(source_id, SOURCE_FALLBACK)
            accent = (light, dark)[theme]
            avatar = (avatar_light or light, avatar_dark or dark)[theme]
            key = f"ColorSource{pascal(source_id)}"
            colors[key] = accent
            colors[key + "Avatar"] = avatar
            colors[key + "OnAvatar"] = initial
            for surface in surfaces:
                if palette.contrast(accent, surface) < 3.0:
                    problems.append(f"{key} ({name}) {accent} on {surface}: {palette.contrast(accent, surface):.2f} < 3")
            if palette.contrast(initial, avatar) < 4.5:
                problems.append(f"{key}OnAvatar ({name}): {palette.contrast(initial, avatar):.2f} < 4.5")
        fallback = SOURCE_FALLBACK[theme]
        colors["ColorSourceUnknown"] = fallback
        colors["ColorSourceUnknownAvatar"] = fallback
        colors["ColorSourceUnknownOnAvatar"] = SOURCE_FALLBACK[4]
        write(f"Tokens.Sources.{name}.xaml", color_lines(colors))

    static = []
    static += [f'    <x:Double x:Key="{k}">{v}</x:Double>' for k, v in SPACE.items()]
    static += [""] + [f'    <x:Double x:Key="{k}">{v}</x:Double>' for k, v in RADIUS.items()]
    static += [f'    <CornerRadius x:Key="{k}Corner">{v}</CornerRadius>' for k, v in RADIUS.items()]
    static += [f'    <x:Int32 x:Key="{k}">{v}</x:Int32>' for k, v in STATIC_INTS.items()]
    static += [""] + [f'    <x:Double x:Key="{k}">{number(v)}</x:Double>' for k, v in STATIC_DOUBLES.items()]
    static += [""] + [f'    <Thickness x:Key="{k}">{v}</Thickness>' for k, v in STATIC_THICKNESS.items()]
    static += [""]
    for type_name, (size, line_height, tracking) in TYPE.items():
        if type_name not in DENSITY_TYPES:
            static.append(f'    <x:Double x:Key="Type{type_name}Size">{number(size)}</x:Double>')
            static.append(f'    <x:Double x:Key="Type{type_name}LineHeight">{number(line_height)}</x:Double>')
        static.append(f'    <x:Double x:Key="Type{type_name}Tracking">{number(tracking)}</x:Double>')
    write("Tokens.Static.xaml", static)

    for index, name in ((0, "Comfortable"), (1, "Compact")):
        lines = [f'    <x:Double x:Key="{k}">{v[index]}</x:Double>' for k, v in DENSITY.items()]
        lines += [f'    <Thickness x:Key="{k}">{v[index]}</Thickness>' for k, v in DENSITY_THICKNESS.items()]
        lines.append("")
        for type_name in sorted(DENSITY_TYPES):
            size, line_height, _ = TYPE[type_name]
            if index == 1:
                size, line_height = TYPE_COMPACT[type_name]
            lines.append(f'    <x:Double x:Key="Type{type_name}Size">{number(size)}</x:Double>')
            lines.append(f'    <x:Double x:Key="Type{type_name}LineHeight">{number(line_height)}</x:Double>')
        write(f"Tokens.{name}.xaml", lines)

    for line in problems:
        print("WARNING:", line)
    print(f"tokens -> {OUT}")


if __name__ == "__main__":
    main()

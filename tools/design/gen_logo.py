"""Generates the OnionLLM mark (DESIGN.md §7.7): three concentric arcs open ~40° at the top + a centre dot.

    python tools/design/gen_logo.py

Outputs the app icon (background + foreground), splash and in-app logo SVGs. Colours come from the palette in
DESIGN.md §2.1.1–2.1.2 (the generator is, like gen_tokens.py, a place where literals are allowed).
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "OnionLLM" / "Resources"

ONION = {"200": "#F5C6DF", "300": "#EB9BC6", "400": "#DA6AA7", "500": "#C0448A", "700": "#86295E",
         "950": "#2E0D20"}
HUSK_400 = "#F2C14E"
ON_LIGHT = (ONION["700"], ONION["500"], ONION["300"])  # outer -> inner, light background
ON_DARK = (ONION["400"], ONION["300"], ONION["200"])   # outer -> inner, dark background
CANVAS_LIGHT = "#F7F7F9"

GAP_DEGREES = 40


def mark(size: float, colours: tuple[str, str, str], offset: float = 0, dot: bool = True) -> str:
    """Mark drawn in a square of side `size` starting at (offset, offset). Grid 24: stroke 2, radii 11/7/3, dot 1."""
    unit = size / 24
    cx = cy = offset + size / 2
    stroke = 2 * unit
    half = math.radians(GAP_DEGREES / 2)
    parts = []
    for radius, colour in zip((11 * unit, 7 * unit, 3 * unit), colours):
        x1, y1 = cx + radius * math.sin(half), cy - radius * math.cos(half)
        x2, y2 = cx - radius * math.sin(half), cy - radius * math.cos(half)
        parts.append(
            f'<path d="M{x1:.3f} {y1:.3f} A{radius:.3f} {radius:.3f} 0 1 1 {x2:.3f} {y2:.3f}" fill="none" '
            f'stroke="{colour}" stroke-width="{stroke:.3f}" stroke-linecap="round"/>')
    if dot:
        parts.append(f'<circle cx="{cx:.3f}" cy="{cy:.3f}" r="{unit:.3f}" fill="{HUSK_400}"/>')
    return "\n  ".join(parts)


def svg(width: int, height: int, body: str) -> str:
    return (f'<?xml version="1.0" encoding="UTF-8"?>\n'
            f'<!-- Generated by tools/design/gen_logo.py (DESIGN.md §7.7). Do not edit by hand. -->\n'
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">\n'
            f'  {body}\n</svg>\n')


def main() -> None:
    # In-app logo (sidebar, onboarding, „O aplikacji”): full colour, light and dark backgrounds, 24-grid.
    (RES / "Images" / "onion_logo.svg").write_text(svg(24, 24, mark(24, ON_LIGHT)), encoding="utf-8")
    (RES / "Images" / "onion_logo_dark.svg").write_text(svg(24, 24, mark(24, ON_DARK)), encoding="utf-8")

    # App icon: rounded square with onion.950 → onion.700 gradient + mark in dark-background colours, 60% of the area.
    background = (
        '<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">'
        f'<stop offset="0" stop-color="{ONION["950"]}"/><stop offset="1" stop-color="{ONION["700"]}"/>'
        '</linearGradient></defs>\n  <rect width="456" height="456" rx="96" fill="url(#g)"/>')
    (RES / "AppIcon" / "appicon.svg").write_text(svg(456, 456, background), encoding="utf-8")
    side = 456 * math.sqrt(0.6)
    (RES / "AppIcon" / "appiconfg.svg").write_text(
        svg(456, 456, mark(side, ON_DARK, offset=(456 - side) / 2)), encoding="utf-8")

    # Splash: the mark at 128 on bg.canvas (background colour is set in the csproj), no text.
    (RES / "Splash" / "splash.svg").write_text(svg(128, 128, mark(128, ON_LIGHT)), encoding="utf-8")
    print("logo -> Resources/Images, AppIcon, Splash")


if __name__ == "__main__":
    main()

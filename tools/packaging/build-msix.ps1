<#
.SYNOPSIS
    Builds the OnionLLM MSIX installer (Windows), optionally signs it and registers it for a local test.

.DESCRIPTION
    Output: artifacts\msix\OnionLLM_<version>_Test\OnionLLM_<version>_x64.msix + Dependencies\x64\Microsoft.WindowsAppRuntime.2.msix
    and Install.ps1 generated by the MSIX tooling.

    Signing: the package Publisher (Package.appxmanifest) is "CN=OnionLLM". For a self-signed test certificate use
    -CreateTestCertificate (CurrentUser\My, exported to .signing\ — never committed). To install the signed .msix on a
    machine, its certificate (.cer) must be trusted — once, as administrator:
        Import-Certificate -FilePath .signing\OnionLLM-test.cer -CertStoreLocation Cert:\LocalMachine\TrustedPeople
    then double-click the .msix (App Installer) or:  Add-AppxPackage -Path <msix> -DependencyPath <runtime msix>

    -Register: Developer Mode only — registers the built layout (no signature needed) to test the packaged app;
    remove with:  Get-AppxPackage *onionllm* | Remove-AppxPackage

.EXAMPLE
    powershell -NoProfile -File tools\packaging\build-msix.ps1 -CreateTestCertificate -Sign
.EXAMPLE
    powershell -NoProfile -File tools\packaging\build-msix.ps1 -Configuration Debug -Register
#>
param(
    [ValidateSet('Release', 'Debug')]
    [string]$Configuration = 'Release',
    [switch]$Sign,
    [switch]$CreateTestCertificate,
    [string]$CertificatePath,
    [string]$CertificatePassword,
    [switch]$Register
)

$ErrorActionPreference = 'Stop'
$root = Resolve-Path (Join-Path $PSScriptRoot '..\..')
$project = Join-Path $root 'OnionLLM\OnionLLM.csproj'
$framework = 'net11.0-windows10.0.19041.0'
$signing = Join-Path $root '.signing'
$output = Join-Path $root "artifacts\msix\$Configuration\"

if ($CreateTestCertificate) {
    New-Item -ItemType Directory -Force -Path $signing | Out-Null
    $password = [Convert]::ToBase64String((1..24 | ForEach-Object { Get-Random -Maximum 256 }) -as [byte[]])
    $certificate = New-SelfSignedCertificate -Type Custom -Subject 'CN=OnionLLM' -KeyUsage DigitalSignature `
        -FriendlyName 'OnionLLM test signing' -CertStoreLocation 'Cert:\CurrentUser\My' `
        -TextExtension @('2.5.29.37={text}1.3.6.1.5.5.7.3.3', '2.5.29.19={text}') -NotAfter (Get-Date).AddYears(2)
    $secure = ConvertTo-SecureString -String $password -Force -AsPlainText
    Export-PfxCertificate -Cert $certificate -FilePath (Join-Path $signing 'OnionLLM-test.pfx') -Password $secure | Out-Null
    Export-Certificate -Cert $certificate -FilePath (Join-Path $signing 'OnionLLM-test.cer') | Out-Null
    Set-Content -Path (Join-Path $signing 'password.txt') -Value $password -NoNewline
    Write-Host "Test certificate: $($certificate.Thumbprint) -> $signing"
}

$arguments = @('publish', $project, '-f', $framework, '-c', $Configuration, '-p:RuntimeIdentifierOverride=win-x64',
    '-p:WindowsPackageType=MSIX', "-p:AppxPackageDir=$output", '-nologo', '-v', 'q')
if ($Sign) {
    if (-not $CertificatePath) { $CertificatePath = Join-Path $signing 'OnionLLM-test.pfx' }
    if (-not $CertificatePassword) { $CertificatePassword = Get-Content (Join-Path $signing 'password.txt') -Raw }
    $arguments += @('-p:AppxPackageSigningEnabled=true', "-p:PackageCertificateKeyFile=$CertificatePath",
        "-p:PackageCertificatePassword=$CertificatePassword")
}

& dotnet @arguments
if ($LASTEXITCODE -ne 0) { throw "dotnet publish failed ($LASTEXITCODE)" }

$msix = Get-ChildItem -Path $output -Recurse -Filter 'OnionLLM_*_x64.msix' | Sort-Object LastWriteTime | Select-Object -Last 1
Write-Host "MSIX: $($msix.FullName)"

if ($Register) {
    $layout = Get-ChildItem -Path (Join-Path $root "OnionLLM\bin\$Configuration\$framework\win-x64") -Recurse -Filter 'AppxManifest.xml' |
        Sort-Object LastWriteTime | Select-Object -Last 1
    Add-AppxPackage -Register $layout.FullName -ForceApplicationShutdown
    Write-Host "Registered: $($layout.DirectoryName) — run 'onionllm-app' or OnionLLM from Start."
}
